// Writes src/components/icons.generated.ts: the Lucide icons the app uses, taken from
// Iconify's data. The whole set weighs ~600 KB, so the app only bundles these.
// To add an icon, add its name (see https://icon-sets.iconify.design/lucide/) and run `pnpm icons`.
import { writeFile } from 'node:fs/promises';

import { icons as lucide } from '@iconify-json/lucide';
import lucidePackage from '@iconify-json/lucide/package.json' with { type: 'json' };
import { getIconData } from '@iconify/utils';
import * as prettier from 'prettier';

const names = [
  'calendar',
  'camera',
  'check',
  'chevron-down',
  'chevron-left',
  'chevron-right',
  'circle-alert',
  'clock',
  'credit-card',
  'eye',
  'eye-off',
  'house',
  'image',
  'info',
  'lock',
  'map-pin',
  'paw-print',
  'phone',
  'plus',
  'rotate-cw',
  'search',
  'sliders-horizontal',
  'star',
  'user',
  'x',
];

const bodies = names.map((name) => {
  const icon = getIconData(lucide, name);
  if (!icon) throw new Error(`Lucide has no icon named "${name}"`);
  if ((icon.width ?? lucide.width) !== 24 || (icon.height ?? lucide.height) !== 24) {
    throw new Error(`"${name}" isn't 24 × 24, and Icon draws every icon in a 24 × 24 box`);
  }
  return [name, icon.body];
});

const target = new URL('../src/components/icons.generated.ts', import.meta.url);
const source = `// Generated by scripts/generate-icons.mjs from @iconify-json/lucide ${lucidePackage.version}.
// Don't edit it: add the icon's name to that script and run \`pnpm icons\`.

export const icons = ${JSON.stringify(Object.fromEntries(bodies))} as const;

export type IconName = keyof typeof icons;
`;
const options = await prettier.resolveConfig(target);
await writeFile(target, await prettier.format(source, { ...options, parser: 'typescript' }));
console.log(`Wrote ${names.length} icons to ${target.pathname}`);
